/**
 * Numerical features describing how long a task spends idle
 * during the standard operational calendar.
 *
 * Generated by metricsExtractorService and later scored by
 * the anomaly detector.
 */
export interface WaitingMetrics {
  taskId: string;

  /** Total operational hours spent in waiting + blocked throughout task lifetime */
  idleHours: number;

  /** Number of separate waiting/blocked periods */
  idleSegmentCount: number;

  /** Current operational hours spent idle (0 if task is active or completed) */
  currentIdleHours: number;
}

/**
 * Numerical features describing ownership gaps between assignees.
 *
 * A handoff gap is measured only when a task becomes completely
 * unassigned and later receives a new assignee.
 */
export interface HandoffMetrics {
  taskId: string;

  /** Number of detected ownership gaps followed by a new assignee. */
  handoffCount: number;

  /** Mean duration of the detected ownership gaps. */
  averageGapHours: number;

  /** Longest detected ownership gap. */
  maxGapHours: number;

  /**
   * Mean time spent in each status segment before the next
   * status transition. Used as supporting workflow-delay context.
   */
  statusTransitionDelayHours: number;
}

/**
 * Numerical features describing developer context switching.
 * One object per user.
 */
export interface FocusMetrics {
  userId: string;

  /** Current number of tasks assigned and in progress */
  concurrentInProgress: number;

  /** Number of distinct tasks this user started working on */
  tasksStarted: number;
}

/**
 * Complete feature set extracted for a project.
 * This is the direct input to anomalyDetectionService.
 */
export interface ProjectMetrics {
  waiting: WaitingMetrics[];
  handoffs: HandoffMetrics[];
  focus: FocusMetrics[];
}

export type AnomalyType = "waiting" | "handoff" | "focus";

export interface AnomalyDetectionResult {
  entityId: string;
  anomalyType: AnomalyType;
  score: number;
  isAnomaly: boolean;
  threshold: number;
  metrics: WaitingMetrics | HandoffMetrics | FocusMetrics;
  dominantFeature: string | null;
}

export interface ProjectAnomalyResults {
  waiting: AnomalyDetectionResult[];
  handoffs: AnomalyDetectionResult[];
  focus: AnomalyDetectionResult[];
}


